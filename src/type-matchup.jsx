const seqRef = { n: 0 };
const blank = () => ({ id: ++seqRef.n, label: "", t1: "", t2: "", ability: "", speed: "" });
const typesOf = (m) => [m.t1, m.t2].filter(Boolean);
const named = (m, fallback) => m.label.trim() || fallback;

/* Turns a library entry into a filled-in row. */
function rowFrom(entry) {
  return {
    id: ++seqRef.n,
    label: entry.label,
    t1: entry.types[0] ?? "",
    t2: entry.types[1] ?? "",
    ability: entry.abilities[0] ?? "",
    speed: entry.speed == null ? "" : String(entry.speed),
  };
}

/* Search, optionally scoped to one game. A Pokémon counts as in a game when
   the species appears in that game's dex and the form existed by then. */
function lookup(text, gameId) {
  const q = text.trim().toLowerCase();
  if (!q || !HAS_LIBRARY) return [];
  const game = GAMES.find((g) => g.id === gameId);
  return POKEMON
    .filter((e) => {
      if (game && !(e.groups.includes(game.group) && e.since <= game.order)) return false;
      return e.label.toLowerCase().includes(q) || e.name.includes(q);
    })
    .sort((a, b) => a.label.toLowerCase().indexOf(q) - b.label.toLowerCase().indexOf(q)
                 || a.label.length - b.label.length)
    .slice(0, 6);
}

/* A select replacement you can type into. Native dropdowns are unusable
   once a list runs past a dozen entries, and the game list has 53. */
function Picker({ value, options, onChange, placeholder, label, tone }) {
  const [q, setQ] = useState("");
  const [open, setOpen] = useState(false);
  const current = options.find((o) => o.value === value);

  const hits = open
    ? options.filter((o) => o.label.toLowerCase().includes(q.trim().toLowerCase())).slice(0, 8)
    : [];

  function pick(option) {
    onChange(option.value);
    setQ("");
    setOpen(false);
  }

  return (
    <div className="us-picker">
      <input
        className={`us-text ${tone ?? ""}`}
        value={open ? q : (current?.label ?? "")}
        onChange={(e) => { setQ(e.target.value); setOpen(true); }}
        onFocus={() => { setQ(""); setOpen(true); }}
        onBlur={() => setTimeout(() => setOpen(false), 120)}
        onKeyDown={(e) => {
          if (e.key === "Escape") { setOpen(false); e.target.blur(); }
          if (e.key === "Enter" && hits.length) { e.preventDefault(); pick(hits[0]); }
        }}
        placeholder={placeholder}
        aria-label={label}
      />
      {hits.length > 0 && (
        <ul className="us-suggest us-picker-list">
          {hits.map((o) => (
            <li key={o.value || "_none"}>
              {/* mousedown, not click: blur would close the list first */}
              <button onMouseDown={(e) => { e.preventDefault(); pick(o); }}>
                <span style={{ color: o.color }}>{o.label}</span>
                {o.hint && <span className="us-suggest-t">{o.hint}</span>}
              </button>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

/* One editable row. Used for party members and the opponent alike. */
function MonRow({ mon, onChange, onRemove, placeholder, game }) {
  const set = (k) => (e) => onChange({ ...mon, [k]: e.target.value });
  const [open, setOpen] = useState(false);
  const hits = open ? lookup(mon.label, game) : [];

  /* Picking from the library fills the row in; every field stays editable
     afterwards, so an odd build is still yours to correct. */
  function choose(entry) {
    onChange({ ...rowFrom(entry), id: mon.id });
    setOpen(false);
  }

  return (
    <div className="us-row">
      <div className="us-row-line">
        <input
          className="us-text"
          value={mon.label}
          onChange={(e) => { set("label")(e); setOpen(true); }}
          onFocus={() => setOpen(true)}
          placeholder={HAS_LIBRARY ? "Search a Pokémon…" : placeholder}
          aria-label={HAS_LIBRARY ? "Search a Pokémon" : "Name (optional)"}
        />
        {onRemove && (
          <button className="us-remove" onClick={onRemove} aria-label="Remove">×</button>
        )}
      </div>

      {hits.length > 0 && (
        <ul className="us-suggest">
          {hits.map((e) => (
            <li key={e.name}>
              <button onClick={() => choose(e)}>
                {e.label}
                <span className="us-suggest-t">{e.types.join(" / ")}</span>
              </button>
            </li>
          ))}
        </ul>
      )}

      <div className="us-row-line">
        <Picker
          value={mon.t1}
          options={TYPE_OPTIONS}
          onChange={(v) => onChange({ ...mon, t1: v })}
          placeholder="Type…"
          label="First type"
        />
        <Picker
          value={mon.t2}
          options={TYPE_OPTIONS_2.filter((o) => o.value !== mon.t1)}
          onChange={(v) => onChange({ ...mon, t2: v })}
          placeholder="— none —"
          label="Second type"
        />
      </div>

      <div className="us-row-line">
        <Picker
          value={mon.ability}
          options={ABILITY_OPTIONS}
          onChange={(v) => onChange({ ...mon, ability: v })}
          placeholder="No relevant ability"
          label="Ability"
          tone={ABILITY[mon.ability] ? "live" : ""}
        />
        <input
          className="us-text speed"
          value={mon.speed}
          onChange={set("speed")}
          inputMode="numeric"
          placeholder="Speed"
          aria-label="Speed stat (optional)"
        />
      </div>
    </div>
  );
}

